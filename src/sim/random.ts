/**
 * Seeded random numbers (mulberry32): the same seed always gives the same sequence, so a match can
 * be replayed or kept in sync between players. Returns a function giving numbers in [0, 1).
 */
export function createRandom(seed: number): () => number {
  let state = seed >>> 0;

  return () => {
    state = (state + 0x6d2b79f5) >>> 0;
    let t = state;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);

    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}
